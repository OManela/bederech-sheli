export function moduleIndex(id) {
  return MODULES.findIndex(m => m.id === id);
}

/** A module is unlocked when the previous one is done. */
export function isUnlocked(state, idx) {
  if (idx === 0) return true;
  const prev = MODULES[idx - 1];
  return !!(state.modules[prev.id] && state.modules[prev.id].done);
}

export function currentModule(state) {
  return MODULES.find(m => !(state.modules[m.id] && state.modules[m.id].done)) || null;
}

